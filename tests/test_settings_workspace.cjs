"use strict";
const assert = require("node:assert/strict");
const {open} = require("./fixtures/app_page.cjs");
function openSettings(page) { page.$("session-menu-toggle").click(); page.$("open-interview-settings").click(); }
class UIEvent { constructor(type, options={}) { this.type=type;Object.assign(this,options); } }

async function main() {
  const page = await open({modules:["settings-ui.js"],config:{speech:{enabled:true,default_voice:"marin",voices:[{id:"marin",label:"Marin"},{id:"cedar",label:"Cedar"}]}}});
  page.context.Event = page.context.CustomEvent = UIEvent;
  page.context.queueMicrotask = queueMicrotask;
  const settings = page.window.CollectorSettings;
  assert.equal(page.document.getElementById("open-settings"),null,"There is no second header Settings control");
  assert.equal(page.$("session-menu").querySelector("button").id,"open-interview-settings","Settings is the first menu action");
  for(const id of ["export-session","import-session","export-transcript-menu","submit-process-menu","load-example","reset-session"])assert(page.$("session-menu").contains(page.$(id)),id+" remains available");
  openSettings(page);
  assert(page.$("interview-settings").open, "Settings opens from the unified header menu");
  assert.equal(page.$("preferences-details").hidden,false);
  const tabs = page.document.querySelectorAll("[data-settings-target]").filter(tab => !tab.hidden);
  assert.equal(tabs.length,4);
  for (const tab of tabs) {
    tab.click();
    assert.equal(tab.getAttribute("aria-selected"),"true");
    assert.equal(page.$(tab.dataset.settingsTarget).hidden,false);
    assert.equal(page.document.querySelectorAll('[data-settings-panel]').filter(panel=>!panel.hidden).length,1);
  }
  page.$("settings-tab-context").focus();
  page.$("settings-tab-context").dispatchEvent({type:"keydown",key:"ArrowDown"});
  assert.equal(page.document.activeElement,page.$("settings-tab-data"));
  assert.equal(page.$("data-details").hidden,false);
  page.$("settings-search").input("privacy");
  let results=page.$("settings-search-matches").querySelectorAll("button");
  assert.equal(results.length,1);
  results[0].click();
  assert.equal(page.$("data-details").hidden,false);
  assert.equal(page.document.activeElement,page.$("data-notice"));
  assert.equal(page.$("settings-search").value,"");
  page.$("settings-search").input("definition of done");
  const doneGuide=page.$("settings-search-matches").querySelector("button");
  doneGuide.click();
  assert.equal(page.$("help-guide").hidden,false);
  assert.equal(page.document.activeElement,page.$("definition-of-done"));
  assert.match(page.$("definition-of-done").parentElement.textContent,/Keep a partial interview/);
  page.$("settings-search").input("shortcuts");
  results=page.$("settings-search-matches").querySelectorAll("button");
  assert.equal(results.length,1);
  results[0].click();
  assert.equal(page.$("help-guide").hidden,false);
  assert.equal(page.document.activeElement,page.$("keyboard-shortcuts"),"The finder reaches the keyboard shortcuts");
  page.$("settings-search").input("unfindable-setting");
  assert.match(page.$("settings-search-count").textContent,/No settings match “unfindable-setting”/);
  assert.equal(page.$("settings-search-suggestions").hidden,false,"An empty result offers searches that do match");
  assert.equal(page.$("interview-settings").dataset.searching,"true","No section is marked current while results are listed");
  page.document.querySelector('[data-settings-suggest="voice"]').click();
  assert.equal(page.$("settings-search").value,"voice");
  assert(page.$("settings-search-matches").querySelectorAll("button").length>0);
  assert.equal(page.$("settings-search-suggestions").hidden,true);
  assert.equal(page.document.activeElement,page.$("settings-search"),"A suggestion leaves the finder ready for more typing");
  page.$("interview-settings").dispatchEvent({type:"keydown",key:"Escape"});
  assert.equal(page.$("settings-search-results").hidden,true);
  assert(page.$("interview-settings").open,"Escape clears search before closing Settings");
  assert.equal(page.$("interview-settings").dataset.searching,undefined);
  settings.show("preferences-details");
  const dark=page.document.querySelectorAll('input[name="settings-theme"]').find(radio=>radio.value==="dark");
  dark.checked=true;dark.dispatchEvent({type:"change"});
  assert.equal(page.$("theme-select").value,"dark");
  page.$("voice-picker-toggle").click();
  assert.equal(page.$("voice-picker-toggle").getAttribute("aria-expanded"),"true");
  page.$("voice-picker-search").input("Cedar");
  const cedar=page.$("voice-picker-list").querySelector('[role="option"]');
  assert.equal(cedar.textContent,"Cedar");cedar.click();
  assert.equal(page.state.voiceChoice,"ai:cedar");
  assert.equal(page.$("voice-picker-name").textContent,"Cedar");
  assert.equal(page.document.activeElement,page.$("voice-picker-toggle"));
  page.$("voice-select").disabled=true;settings.refreshVoice();
  assert.equal(page.$("voice-picker-toggle").disabled,true);
  assert.equal(page.$("voice-picker-panel").hidden,true);
  settings.show("help-guide");
  page.$("close-interview-settings").click();
  assert.equal(page.document.activeElement,page.$("session-menu-toggle"));
  openSettings(page);
  assert.equal(page.$("help-guide").hidden,false,"The last section is kept for quick return");
  page.$("close-interview-settings").click();
  page.$("open-context").click();
  assert.equal(page.$("context-details").hidden,false);
  assert.equal(page.$("settings-tab-context").getAttribute("aria-selected"),"true");
  assert.equal(page.document.activeElement,page.$("process-owner"));
  assert.equal(page.requests.filter(row=>/interview|voice-session|conversation/.test(row.url)).length,0,"Browsing Settings never starts an interview or voice session");
  const mobile=await open({narrow:true,modules:["settings-ui.js"]});
  mobile.context.Event=mobile.context.CustomEvent=UIEvent;
  openSettings(mobile);
  mobile.$("settings-tab-preferences").focus();
  mobile.$("settings-tab-preferences").dispatchEvent({type:"keydown",key:"ArrowDown"});
  assert.equal(mobile.document.activeElement,mobile.$("settings-tab-data"),"Down moves to the same column in mobile navigation");
  assert.equal(mobile.$("interview-settings").querySelector('[role="tablist"]').getAttribute("aria-orientation"),"horizontal");
  console.log("Settings: direct entry, all four sections, keyboard navigation, finder and its suggestions, appearance, voice picker, disabled state and source context passed.");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
